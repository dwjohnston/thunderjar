// Reads parameter names and harness family version/model maps under
// `test-case-parameters/` and renders `_generated/parameter-names.d.ts` —
// spec/055-declaring-test-cases.md#typed-names.

import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { InvalidConfigError, loadDeclaration, type Problem } from "../../../project/config.ts";

interface HarnessFamilyNames {
  versions: string[];
  models: string[];
}

export interface ParameterNames {
  baseImages: string[];
  codeStates: string[];
  promptSets: string[];
  tasks: Record<string, string[]>; // task name -> initial prompt names
  harnessFamilies: Record<string, HarnessFamilyNames>;
}

async function listDirNames(dir: string): Promise<string[]> {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
  } catch {
    return [];
  }
}

async function listFileStems(dir: string): Promise<string[]> {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
      .map((entry) => entry.name.slice(0, -".ts".length))
      .sort();
  } catch {
    return [];
  }
}

async function loadFamilyNames(root: string, family: string, problems: Problem[]): Promise<HarnessFamilyNames> {
  const familyDir = `test-case-parameters/harnessModels/${family}`;
  const models = await loadDeclaration(root, `${familyDir}/models.ts`, "declareHarnessModels", problems);
  const versions = await loadDeclaration(root, `${familyDir}/versions.ts`, "declareHarnessVersions", problems);
  return {
    models: Object.keys(models ?? {}).sort(),
    versions: Object.keys(versions ?? {}).sort(),
  };
}

/** Scans a `.thunderjar/` root's `test-case-parameters/` folder for declared names. */
export async function collectParameterNames(root: string): Promise<ParameterNames> {
  const parameters = join(root, "test-case-parameters");

  const [baseImages, codeStates, promptSets, taskNames, familyNames] = await Promise.all([
    listDirNames(join(parameters, "baseImages")),
    listDirNames(join(parameters, "codeStates")),
    listDirNames(join(parameters, "promptSets")),
    listDirNames(join(parameters, "tasks")),
    listDirNames(join(parameters, "harnessModels")),
  ]);

  const tasks: Record<string, string[]> = {};
  for (const task of taskNames) {
    tasks[task] = await listFileStems(join(parameters, "tasks", task, "initial-prompts"));
  }

  const harnessFamilies: Record<string, HarnessFamilyNames> = {};
  const problems: Problem[] = [];
  for (const family of familyNames) {
    harnessFamilies[family] = await loadFamilyNames(root, family, problems);
  }
  if (problems.length > 0) throw new InvalidConfigError(problems);

  return { baseImages, codeStates, promptSets, tasks, harnessFamilies };
}

function literalUnion(names: string[]): string {
  return names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | ");
}

/** Renders `_generated/parameter-names.d.ts`'s contents from scanned names. */
export function renderParameterNames(names: ParameterNames): string {
  const lines = [
    "// _generated/parameter-names.d.ts — generated by `thunderjar generate`, not edited",
    "",
    `type BaseImageName = ${literalUnion(names.baseImages)};`,
    `type CodeStateName = ${literalUnion(names.codeStates)};`,
    `type PromptSetName = ${literalUnion(names.promptSets)};`,
    `type TaskName = ${literalUnion(Object.keys(names.tasks))};`,
  ];

  const tasks = Object.entries(names.tasks);
  if (tasks.length === 0) {
    lines.push("type InitialPromptNames = Record<string, never>;");
  } else {
    lines.push("type InitialPromptNames = {");
    for (const [task, prompts] of tasks) {
      lines.push(`  ${JSON.stringify(task)}: ${literalUnion(prompts)};`);
    }
    lines.push("};");
  }

  const pairs = Object.entries(names.harnessFamilies)
    .filter(([, { versions, models }]) => versions.length > 0 && models.length > 0)
    .map(([family, { versions, models }]) => "`" + family + "@${" + literalUnion(versions) + "}/${" + literalUnion(models) + "}`");
  if (pairs.length === 0) {
    lines.push("type HarnessModelName = never;");
  } else if (pairs.length === 1) {
    lines.push(`type HarnessModelName = ${pairs[0]};`);
  } else {
    lines.push("type HarnessModelName =");
    lines.push(...pairs.map((pair) => `  | ${pair}`));
    lines[lines.length - 1] += ";";
  }
  lines.push("");

  return lines.join("\n");
}

/** Scans `root` and writes `_generated/parameter-names.d.ts`, returning its path. */
export async function writeGeneratedTypes(root: string): Promise<{ path: string; content: string }> {
  const names = await collectParameterNames(root);
  const content = renderParameterNames(names);
  const path = join(root, "_generated", "parameter-names.d.ts");
  await mkdir(join(root, "_generated"), { recursive: true });
  await writeFile(path, content);
  return { path, content };
}
