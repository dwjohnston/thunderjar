// Reads the names declared under `.thunderjar/parameters/`, and renders them as the
// global types of `_generated/parameterNames.d.ts`.
import type { HarnessDeclaration } from "../../../api/declarations.ts";
import { foldersIn, PARAMETERS as P, tsFilesIn } from "../../../config/folders.ts";
import { modelVariants } from "../../../config/harnessModels.ts";
import { loadDeclaration, type Problem } from "../../../config/loader.ts";

export const GENERATED_PATH = "_generated/parameterNames.d.ts";

export type ParameterNames = {
  baseImages: string[];
  codeStates: string[];
  promptSets: string[];
  /** Each task's initial prompts, by task name. */
  tasks: Record<string, string[]>;
  /**
   * The harness folders, each with the names its models make, e.g. `openai/gpt-6.1-sol/high`, or
   * undefined if any model goes: a pair is `<harness>/<name>`.
   */
  harnesses: Record<string, string[] | undefined>;
};

/**
 * The names each harness's models make, by harness folder: undefined, any model, for one that
 * declares none, or fails to load, adding to `problems`.
 */
async function harnessNames(root: string, problems: Problem[]): Promise<Record<string, string[] | undefined>> {
  const names: Record<string, string[] | undefined> = {};
  for (const harness of await foldersIn(root, `${P}/harnessModels`)) {
    const declaration = (await loadDeclaration(root, `${P}/harnessModels/${harness}/index.ts`, "declareHarness", problems)) as
      | Partial<HarnessDeclaration>
      | undefined;
    const models = declaration?.models;
    names[harness] =
      models === undefined ? undefined : Object.entries(models).flatMap(([modelId, settings]) => modelVariants(modelId, settings).map(({ name }) => name));
  }
  return names;
}

/**
 * The names declared in the `.thunderjar/` folder `root`, from its folders and files, and the
 * harnesses' models, which are loaded. A harness that fails to load adds to `problems`.
 */
export async function collectParameterNames(root: string, problems: Problem[] = []): Promise<ParameterNames> {
  const tasks: Record<string, string[]> = {};
  for (const task of await foldersIn(root, `${P}/tasks`)) {
    tasks[task] = await tsFilesIn(root, `${P}/tasks/${task}/initial-prompts`);
  }
  return {
    baseImages: await foldersIn(root, `${P}/baseImages`),
    codeStates: await foldersIn(root, `${P}/codeStates`),
    promptSets: await foldersIn(root, `${P}/promptSets`),
    tasks,
    harnesses: await harnessNames(root, problems),
  };
}

const union = (names: string[]) => (names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | "));

function initialPromptType(tasks: Record<string, string[]>): string {
  const entries = Object.entries(tasks);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([task, prompts]) => `  ${JSON.stringify(task)}: ${union(prompts)};\n`).join("")}}`;
}

/** Each harness's pairs: its models' names, or any model if it has none. */
function harnessModelType(harnesses: Record<string, string[] | undefined>): string {
  const entries = Object.entries(harnesses);
  if (entries.every(([, names]) => names === undefined)) return " `${HarnessName}/${string}`";
  const pairs = entries.flatMap(([harness, names]) => (names === undefined ? [`\`${harness}/\${string}\``] : names.map((name) => JSON.stringify(`${harness}/${name}`))));
  return pairs.length === 0 ? " never" : pairs.map((pair) => `\n  | ${pair}`).join("");
}

/** The contents of `_generated/parameterNames.d.ts`. */
export function renderParameterNames(names: ParameterNames): string {
  return `// Generated by \`thunderjar generate\` from .thunderjar/${P}/. Don't edit it: run that again.

type BaseImageName = ${union(names.baseImages)};
type CodeStateName = ${union(names.codeStates)};
type PromptSetName = ${union(names.promptSets)};
type TaskName = ${union(Object.keys(names.tasks))};
type InitialPromptNames = ${initialPromptType(names.tasks)};
type HarnessName = ${union(Object.keys(names.harnesses))};
type HarnessModelName =${harnessModelType(names.harnesses)};

interface ThunderjarParameterNames {
  baseImage: BaseImageName;
  codeState: CodeStateName;
  promptSet: PromptSetName;
  task: TaskName;
  initialPrompt: InitialPromptNames;
  harnessModel: HarnessModelName;
}
`;
}

/**
 * Writes `<root>/_generated/parameterNames.d.ts` from the names declared in `root`. Returns the
 * problems of each harness that failed to load, whose pairs then take any model.
 */
export async function writeParameterNames(root: string): Promise<Problem[]> {
  const problems: Problem[] = [];
  await Bun.write(`${root}/${GENERATED_PATH}`, renderParameterNames(await collectParameterNames(root, problems)));
  return problems;
}
