// Reads the names declared under `.thunderjar/test-case-parameters/`, and renders them as the
// global types of `_generated/parameterNames.d.ts`.
import { Glob } from "bun";
import { loadDefault } from "../../../config/loader.ts";

export const GENERATED_PATH = "_generated/parameterNames.d.ts";

const P = "test-case-parameters";

export type HarnessNames = { versions: string[]; models: string[] };

export type ParameterNames = {
  baseImages: string[];
  codeStates: string[];
  promptSets: string[];
  /** Each task's initial prompts, by task name. */
  tasks: Record<string, string[]>;
  /** Each harness's versions and models, by harness name. */
  harnesses: Record<string, HarnessNames>;
};

const sorted = (names: Iterable<string>) => [...new Set(names)].toSorted();

/** The folders directly in `dir`, sorted. None if `dir` doesn't exist. */
async function foldersIn(dir: string): Promise<string[]> {
  const folders: string[] = [];
  try {
    for (const name of new Glob("*").scanSync({ cwd: dir, onlyFiles: false })) {
      if ((await Bun.file(`${dir}/${name}`).stat()).isDirectory()) folders.push(name);
    }
  } catch {
    return [];
  }
  return sorted(folders);
}

/** The names of the `.ts` files directly in `dir`, without `.ts`, sorted. */
function tsFilesIn(dir: string): string[] {
  try {
    return sorted([...new Glob("*.ts").scanSync({ cwd: dir })].map((path) => path.slice(0, -".ts".length)));
  } catch {
    return [];
  }
}

async function keysOfDefault(root: string, path: string): Promise<string[]> {
  if (!(await Bun.file(`${root}/${path}`).exists())) return [];
  return sorted(Object.keys((await loadDefault(root, path)) ?? {}));
}

/** The names declared in the `.thunderjar/` folder `root`. */
export async function collectParameterNames(root: string): Promise<ParameterNames> {
  const tasks: Record<string, string[]> = {};
  for (const task of await foldersIn(`${root}/${P}/tasks`)) {
    tasks[task] = tsFilesIn(`${root}/${P}/tasks/${task}/initial-prompts`);
  }
  const harnesses: Record<string, HarnessNames> = {};
  for (const harness of await foldersIn(`${root}/${P}/harnessModels`)) {
    const dir = `${P}/harnessModels/${harness}`;
    harnesses[harness] = {
      versions: await keysOfDefault(root, `${dir}/versions.ts`),
      models: await keysOfDefault(root, `${dir}/models.ts`),
    };
  }
  return {
    baseImages: await foldersIn(`${root}/${P}/baseImages`),
    codeStates: await foldersIn(`${root}/${P}/codeStates`),
    promptSets: await foldersIn(`${root}/${P}/promptSets`),
    tasks,
    harnesses,
  };
}

const union = (names: string[]) => (names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | "));

/** Every `<harness>@<version>/<model>` the harnesses declare, to follow `type HarnessModelName =`: one on the same line, more on lines of their own. */
function harnessModelType(harnesses: Record<string, HarnessNames>): string {
  const pairs = Object.entries(harnesses)
    .filter(([, { versions, models }]) => versions.length > 0 && models.length > 0)
    .map(([harness, { versions, models }]) => `\`${harness}@\${${union(versions)}}/\${${union(models)}}\``);
  if (pairs.length <= 1) return ` ${pairs[0] ?? "never"}`;
  return pairs.map((pair) => `\n  | ${pair}`).join("");
}

function initialPromptType(tasks: Record<string, string[]>): string {
  const entries = Object.entries(tasks);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([task, prompts]) => `  ${JSON.stringify(task)}: ${union(prompts)};\n`).join("")}}`;
}

/** The contents of `_generated/parameterNames.d.ts`. */
export function renderParameterNames(names: ParameterNames): string {
  return `// Generated by \`thunderjar generate\` from .thunderjar/${P}/. Don't edit it: run that again.

type BaseImageName = ${union(names.baseImages)};
type CodeStateName = ${union(names.codeStates)};
type PromptSetName = ${union(names.promptSets)};
type TaskName = ${union(Object.keys(names.tasks))};
type InitialPromptNames = ${initialPromptType(names.tasks)};
type HarnessModelName =${harnessModelType(names.harnesses)};

interface ThunderjarParameterNames {
  baseImage: BaseImageName;
  codeState: CodeStateName;
  promptSet: PromptSetName;
  task: TaskName;
  initialPrompt: InitialPromptNames;
  harnessModel: HarnessModelName;
}
`;
}

/** Writes `<root>/_generated/parameterNames.d.ts` from the names declared in `root`. */
export async function writeParameterNames(root: string): Promise<void> {
  await Bun.write(`${root}/${GENERATED_PATH}`, renderParameterNames(await collectParameterNames(root)));
}
