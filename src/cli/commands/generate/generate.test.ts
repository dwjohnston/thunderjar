// `thunderjar generate`, through the CLI. It writes into the project, so it runs on a copy of the
// scenario, without the copy's `_generated/`, as in a fresh clone where it's git-ignored.
import { describe, expect, test } from "bun:test";
import { $ } from "bun";
import { copyScenarioProject, thunderjar } from "../../../testing/cli.ts";
import { scenario } from "../../../testing/scenario.ts";

const GENERATED = ".thunderjar/_generated/parameterNames.d.ts";

describe("0201 minimal existing setup", () => {
  test("writes the declared names as global types", async () => {
    await using copy = await copyScenarioProject("0201");
    await $`rm -r ${copy.dir}/.thunderjar/_generated`.quiet();

    const { stdout, stderr, exitCode } = await thunderjar(copy.dir, ["generate"]);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe(`Wrote ${GENERATED}\n`);
    expect(await Bun.file(`${copy.dir}/${GENERATED}`).text()).toBe(`// Generated by \`thunderjar generate\` from .thunderjar/test-case-parameters/. Don't edit it: run that again.

type BaseImageName = "node20";
type CodeStateName = "baseline";
type PromptSetName = "snerk";
type TaskName = "is-prime";
type InitialPromptNames = {
  "is-prime": "plain";
};
type HarnessModelName = \`fake-harness-alpha@\${"1.0.0"}/\${"fake-model-small"}\`;

interface ThunderjarParameterNames {
  baseImage: BaseImageName;
  codeState: CodeStateName;
  promptSet: PromptSetName;
  task: TaskName;
  initialPrompt: InitialPromptNames;
  harnessModel: HarnessModelName;
}
`);
  });

  test("run in a folder below the project, it finds .thunderjar/ above it", async () => {
    await using copy = await copyScenarioProject("0201");
    await $`rm -r ${copy.dir}/.thunderjar/_generated`.quiet();

    const { stdout, stderr, exitCode } = await thunderjar(`${copy.dir}/.thunderjar/test-cases`, ["generate"]);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe("Wrote ../_generated/parameterNames.d.ts\n");
    expect(await Bun.file(`${copy.dir}/${GENERATED}`).exists()).toBe(true);
  });
});

// The type-checked scenarios check in their generated names, as the type-check doesn't run generate.
describe.each(["0201", "0401"])("%s's checked-in generated names", (id) => {
  test("are what generate writes", async () => {
    await using copy = await copyScenarioProject(id);
    await $`rm -r ${copy.dir}/.thunderjar/_generated`.quiet();

    await thunderjar(copy.dir, ["generate"]);

    expect(await Bun.file(`${copy.dir}/${GENERATED}`).text()).toBe(await Bun.file(`${scenario(id)}/${GENERATED}`).text());
  });
});

describe("0101 empty project", () => {
  test("without a .thunderjar/ folder, it fails and says to run init", async () => {
    const { stdout, stderr, exitCode } = await thunderjar(scenario("0101"), ["generate"]);

    expect(stdout).toBe("");
    expect(stderr).toBe(
      "Error: No .thunderjar/ folder in <PROJECT> or any folder above it. Run `thunderjar init` first.\n",
    );
    expect(exitCode).toBe(1);
  });
});

// Every harness's versions and models are loaded, so one broken map fails it for the whole project.
describe("0403 broken harness family", () => {
  test("names the map not wrapped in its declareX, and writes nothing", async () => {
    await using copy = await copyScenarioProject("0403");

    const { stdout, stderr, exitCode } = await thunderjar(copy.dir, ["generate"]);

    expect(stdout).toBe("");
    expect(stderr).toBe(
      "Error: .thunderjar/test-case-parameters/harnessModels/fake-harness-beta/versions.ts: default export is not wrapped in declareHarnessVersions(...).\n",
    );
    expect(exitCode).toBe(1);
    expect(await Bun.file(`${copy.dir}/${GENERATED}`).exists()).toBe(false);
  });
});
