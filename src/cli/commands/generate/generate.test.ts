// `thunderjar generate`, through the CLI, in the checked-in fixtureTests/ scenarios, in place. It
// writes only the gitignored `.thunderjar/_generated/parameter-names.d.ts`, so each test deletes
// that file first, then asserts on what was written. Any of these can be run by hand:
//
//   bun run fixture scenario_2 generate

import { describe, expect, test } from "bun:test";
import { readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { scenario, thunderjar } from "../../../testing/cli.ts";

/** Runs `generate` in `fixtures` with no earlier output left, returning its output and the file. */
async function generateIn(fixtures: string) {
  const path = join(fixtures, ".thunderjar", "_generated", "parameter-names.d.ts");
  await rm(path, { force: true });
  const result = await thunderjar(fixtures, ["generate"]);
  return { ...result, path, content: await readFile(path, "utf8") };
}

describe("scenario_1_minimal_initial_setup", () => {
  const fixtures = scenario("scenario_1_minimal_initial_setup");

  test("generate: one of everything", async () => {
    const { stdout, stderr, exitCode, path, content } = await generateIn(fixtures);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe(`generated ${path}\n`);
    expect(content).toBe(`// _generated/parameter-names.d.ts — generated by \`thunderjar generate\`, not edited

type BaseImageName = "node20";
type CodeStateName = "baseline";
type PromptSetName = "snerk";
type TaskName = "is-prime";
type InitialPromptNames = {
  "is-prime": "plain";
};
type HarnessModelName = \`fake-harness-alpha@\${"1.0.0"}/\${"fake-model-small"}\`;
`);
  });
});

describe("scenario_2_typical_project", () => {
  const fixtures = scenario("scenario_2_typical_project");

  test("generate: sorted unions of every name, and a harness model pair per family", async () => {
    const { stdout, stderr, exitCode, path, content } = await generateIn(fixtures);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe(`generated ${path}\n`);
    expect(content).toBe(`// _generated/parameter-names.d.ts — generated by \`thunderjar generate\`, not edited

type BaseImageName = "node-lts" | "node20";
type CodeStateName = "baseline";
type PromptSetName = "glurk" | "glurk-reworded" | "snerk";
type TaskName = "is-prime" | "no-measures";
type InitialPromptNames = {
  "is-prime": "plain" | "terse";
  "no-measures": "plain";
};
type HarnessModelName =
  | \`fake-harness-alpha@\${"1.0.0" | "1.1.0"}/\${"fake-model-large" | "fake-model-small"}\`
  | \`fake-harness-beta@\${"1.0.0"}/\${"fake-model-large" | "fake-model-small"}\`;
`);
  });

  test("generate: from a folder below the project, writes into the project's .thunderjar/", async () => {
    const below = join(fixtures, ".thunderjar", "test-cases");
    const path = join(fixtures, ".thunderjar", "_generated", "parameter-names.d.ts");
    await rm(path, { force: true });

    const { stdout, stderr, exitCode } = await thunderjar(below, ["generate"]);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe(`generated ${path}\n`);
    expect(await readFile(path, "utf8")).toContain('type CodeStateName = "baseline";');
  });
});

describe("scenario_5_empty_parameter_folders", () => {
  const fixtures = scenario("scenario_5_empty_parameter_folders");

  test("generate: empty parameter folders render as never", async () => {
    const { stdout, stderr, exitCode, path, content } = await generateIn(fixtures);

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);
    expect(stdout).toBe(`generated ${path}\n`);
    expect(content).toBe(`// _generated/parameter-names.d.ts — generated by \`thunderjar generate\`, not edited

type BaseImageName = never;
type CodeStateName = never;
type PromptSetName = never;
type TaskName = never;
type InitialPromptNames = Record<string, never>;
type HarnessModelName = never;
`);
  });
});
